const langSwitch = document.getElementById('langSwitch');
const phoneModal = document.getElementById('phoneModal');
const whatsappAction = document.getElementById('whatsappAction');
const callAction = document.getElementById('callAction');
let activePhone = "";

function applyLanguage(lang){
  const t = translations[lang] || translations.ar;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("is-en", lang === "en");
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if(t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.dataset.i18nAria;
    if(t[key] !== undefined) el.setAttribute("aria-label", t[key]);
  });
  document.querySelectorAll("[data-ar][data-en]").forEach(el => {
    el.textContent = lang === "ar" ? el.dataset.ar : el.dataset.en;
  });
  langSwitch.querySelector(".lang-ar").classList.toggle("active", lang === "ar");
  langSwitch.querySelector(".lang-en").classList.toggle("active", lang === "en");
  localStorage.setItem("siteLang", lang);
}

langSwitch.addEventListener("click", () => {
  applyLanguage(document.documentElement.lang === "ar" ? "en" : "ar");
});

function openPhone(phone){
  if(!phone) return;
  activePhone = phone;
  whatsappAction.href = "https://wa.me/" + phone.replace("+","");
  callAction.href = "tel:" + phone;
  phoneModal.classList.add("show");
  phoneModal.setAttribute("aria-hidden","false");
  document.body.classList.add("modal-open");
}

function openPhoneChooser(){
  phoneModal.classList.add("show");
  phoneModal.setAttribute("aria-hidden","false");
  document.body.classList.add("modal-open");
}

function closePhone(){
  phoneModal.classList.remove("show");
  phoneModal.setAttribute("aria-hidden","true");
  document.body.classList.remove("modal-open");
}

document.querySelectorAll(".phone-action").forEach(el => {
  el.addEventListener("click", e => {
    e.preventDefault();
    openPhone(el.dataset.phone);
  });
});

document.querySelectorAll("[data-phone-cta]").forEach(el => {
  el.addEventListener("click", e => {
    e.preventDefault();
    openPhoneChooser();
  });
});

document.querySelectorAll("[data-close-phone]").forEach(el => {
  el.addEventListener("click", closePhone);
});

document.addEventListener("keydown", e => {
  if(e.key === "Escape") closePhone();
});

document.getElementById('year').textContent = new Date().getFullYear();

const menuButton = document.querySelector('.menu');
menuButton.addEventListener('click', () => {
  const n = document.querySelector('.nav-links');
  const open = n.classList.toggle('mobile-open');
  n.setAttribute("aria-hidden", String(!open));
});

document.querySelectorAll('.nav-links a').forEach(a => {
  a.addEventListener('click', () => document.querySelector('.nav-links').classList.remove('mobile-open'));
});

