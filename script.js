/* ===== Portfolio auto slider ===== */
const portfolioSlider = document.getElementById("portfolioSlider");
if (portfolioSlider) {
  const slides = [...portfolioSlider.querySelectorAll(".portfolio-slide")];
  const dots = [...portfolioSlider.querySelectorAll(".portfolio-dot")];
  const prev = portfolioSlider.querySelector(".portfolio-prev");
  const next = portfolioSlider.querySelector(".portfolio-next");
  let portfolioIndex = 0;
  let portfolioTimer;

  function showPortfolio(index) {
    if (!slides.length) return;
    portfolioIndex = (index + slides.length) % slides.length;

    slides.forEach((slide, i) => {
      slide.classList.toggle("active", i === portfolioIndex);
    });

    dots.forEach((dot, i) => {
      dot.classList.toggle("active", i === portfolioIndex);
    });
  }

  function startPortfolioAuto() {
    clearInterval(portfolioTimer);
    portfolioTimer = setInterval(() => {
      showPortfolio(portfolioIndex + 1);
    }, 4500);
  }

  prev?.addEventListener("click", () => {
    showPortfolio(portfolioIndex - 1);
    startPortfolioAuto();
  });

  next?.addEventListener("click", () => {
    showPortfolio(portfolioIndex + 1);
    startPortfolioAuto();
  });

  dots.forEach((dot, i) => {
    dot.addEventListener("click", () => {
      showPortfolio(i);
      startPortfolioAuto();
    });
  });

  portfolioSlider.addEventListener("mouseenter", () => clearInterval(portfolioTimer));
  portfolioSlider.addEventListener("mouseleave", startPortfolioAuto);

  showPortfolio(0);
  startPortfolioAuto();
}
